public class class_and_object {
    int coffee=10;
    int tea=5;
    public static void main(String[] args) {
        
//SYNTAX: classname  obj = new classname();
        class_and_object obj1=new class_and_object();
        System.out.println(obj1.coffee);

        class_and_object obj2=new class_and_object();
        System.out.println(obj2.tea);
    }
}
